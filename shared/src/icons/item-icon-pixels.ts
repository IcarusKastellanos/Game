function paint(art: string): string[] {
  const rows = art.trim().split('\n');
  if (rows.length !== ICON_PIXEL_SIZE) {
    throw new Error(`item icon height ${rows.length}`);
  }
  const chars: string[][] = [];
  const grid: string[][] = [];
  for (const row of rows) {
    if (row.length !== ICON_PIXEL_SIZE) {
      throw new Error(`item icon width ${row.length}`);
    }
    const rowChars = [...row];
    chars.push(rowChars);
    grid.push(rowChars.map((ch) => {
      const color = PAL[ch];
      if (!color) throw new Error(`item icon palette ${ch}`);
      return color;
    }));
  }
  const empty = PAL['.'];
  const out: string[] = [];
  for (let y = 0; y < ICON_PIXEL_SIZE; y++) {
    for (let x = 0; x < ICON_PIXEL_SIZE; x++) {
      if (grid[y][x] !== empty) {
        out.push(grid[y][x]);
        continue;
      }
      let solid = false;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
        const nx = x + dx;
        const ny = y + dy;
        if (nx < 0 || ny < 0 || nx >= ICON_PIXEL_SIZE || ny >= ICON_PIXEL_SIZE) continue;
        const ch = chars[ny][nx];
        if (ch === '.' || EMISSIVE.has(ch)) continue;
        solid = true;
        break;
      }
      out.push(solid ? OUTLINE : empty);
    }
  }
  return out;
}

const BAKED: Record<string, string[]> = {};
for (const id of Object.keys(ART)) BAKED[id] = paint(ART[id]);

/** Generate a 16×16 sprite for an item. Unknown ids use the category picture. */
export function generateItemIconPixels(itemId: string, category: string, _name = itemId): string[] {
  const key = BAKED[itemId] ? itemId : (CATEGORY_ART[category] ?? 'oil');
  return BAKED[key].slice();
}

/** Use stored pixels or the authored sprite. */
export function resolveItemIconPixels(item: {
  id: string;
  category: string;
  name?: string;
  iconPixels?: string[];
}): string[] {
  if (item.iconPixels?.length === ICON_PIXEL_COUNT) return item.iconPixels;
  return generateItemIconPixels(item.id, item.category, item.name ?? item.id);
}
